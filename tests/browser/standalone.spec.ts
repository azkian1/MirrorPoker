import { expect, test } from '@playwright/test'

test('boots without accounts or external requests and starts a complete bot table', async ({ page }) => {
  const errors: string[] = [], external: string[] = [], failed: string[] = []
  // Optional allowance for scripts injected by the test machine's software.
  // Empty by default; CI rejects every external hostname.
  const ignoredHosts = new Set((process.env.MIRROR_TEST_IGNORED_HOSTS || '').split(',').filter(Boolean))
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    const url = new URL(request.url())
    if (url.protocol.startsWith('http') && url.hostname !== '127.0.0.1' && !ignoredHosts.has(url.hostname)) external.push(url.href)
  })
  page.on('response', response => { if (response.status() >= 400) failed.push(response.url()) })
  await page.goto('/')
  await expect(page.locator('#boot')).toBeHidden()
  await expect(page.getByRole('button', { name: /PLAY VS BOTS/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /HEADS UP|4-MAX|leaderboard/i })).toHaveCount(0)
  await page.getByRole('switch').click()
  await expect(page.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
  await page.screenshot({ path: '.local-check/standalone-menu.png' })
  await page.getByRole('button', { name: /PLAY VS BOTS/ }).click()
  await expect(page.getByRole('dialog', { name: 'One table. Two worlds.' })).toBeVisible()
  await page.getByRole('button', { name: 'PLAY', exact: true }).click()
  await expect(page.locator('.mp-seat:visible')).toHaveCount(4)
  await expect(page.locator('.mp-pot')).toBeVisible()
  await expect(page.locator('.mp-seat-name')).toContainText(['You', 'Vesper', 'Onyx', 'Scarlet'])
  await page.getByRole('button', { name: 'Open table guide' }).click()
  await expect(page.getByRole('heading', { name: 'Card strength' })).toBeVisible()
  await expect(page.locator('.mp-help-ranks')).toHaveCount(2)
  await page.getByRole('button', { name: 'Close help' }).click()
  await page.screenshot({ path: '.local-check/standalone-table.png' })
  await page.getByRole('button', { name: 'Leave table', exact: true }).click()
  await page.getByRole('button', { name: 'Stay', exact: true }).click()
  await expect(page.locator('.mp-pot')).toBeVisible()
  await page.getByRole('button', { name: 'Leave table', exact: true }).click()
  await page.getByRole('button', { name: 'Leave', exact: true }).click()
  await expect(page.getByRole('button', { name: /PLAY VS BOTS/ })).toBeVisible()
  expect(errors).toEqual([])
  expect(external).toEqual([])
  expect(failed).toEqual([])
})

test('runs multiple automatic hands with only local assets', async ({ page }) => {
  await page.goto('/#smoke')
  await expect(page.locator('#boot')).toBeHidden()
  await expect(page.locator('.mp-seat:visible')).toHaveCount(4)
  await expect(page.locator('.mp-last-hand')).toHaveAttribute('data-hand-id', /hand-/, { timeout: 60_000 })
  const firstHand = await page.locator('.mp-last-hand').getAttribute('data-hand-id')
  await expect(page.locator('.mp-last-hand')).not.toHaveAttribute('data-hand-id', firstHand!, { timeout: 60_000 })
  await expect(page.locator('.mp-toast')).toBeHidden()
})

